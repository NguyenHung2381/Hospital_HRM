CREATE INDEX ix_rdr_id_department ON report_department_records (id_department);
CREATE INDEX ix_rdr_id_report ON report_department_records (id_report);
CREATE INDEX ix_rdr_report_department ON report_department_records (id_report, id_department)
	INCLUDE (total_staff, staff_working, recommended_staff, recommended_staff_calc);

