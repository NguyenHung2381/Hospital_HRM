-- ============================================================================
-- Hospital HRM — schema PostgreSQL (chuyển từ SQL Server HRM_HOSPITAL)
-- Mốc tham chiếu: server/db/mssql/schema-snapshot.txt
--
-- Chạy bằng role sở hữu schema (hrm_owner), KHÔNG phải role ứng dụng:
--   psql -U hrm_owner -d hrm_hospital -v ON_ERROR_STOP=1 -f 001_init.sql
--
-- Quy ước khi chuyển:
--  • Tên bảng/cột = tên cũ viết thường, KHÔNG thêm dấu gạch dưới
--    (Departments → departments, UserSessions → usersessions). PostgreSQL tự
--    hạ chữ thường mọi định danh không đặt trong "", nên câu SQL hiện có
--    (FROM Departments, rdr.Id ...) vẫn chạy được mà không phải đổi tên.
--    Ngoại lệ: [Report_Department_Records ] (có dấu cách cuối) →
--    report_department_records; Role_Department_Access.id_deparment (gõ sai)
--    → id_department (bảng chưa dùng trong code, 0 dòng).
--  • Lưu ý: key trong kết quả trả về cũng là chữ thường — cột "Id" cũ sẽ ra
--    key "id" (phải sửa code đọc recordset[0].Id ở giai đoạn 3).
--  • NVARCHAR(n) → varchar(n) (SQL Server tính byte, đã quy về số ký tự);
--    NVARCHAR(MAX) → text; BIT → boolean; TINYINT → smallint + CHECK 0..255;
--    DECIMAL → numeric (giữ nguyên precision/scale);
--    DATETIMEOFFSET và DATETIME2 (đang lưu giờ UTC) → timestamptz.
--  • IDENTITY → GENERATED BY DEFAULT AS IDENTITY (cho phép nạp dữ liệu cũ
--    giữ nguyên id; nạp xong phải setval lại sequence — xem 900_reset_sequences.sql).
--  • So sánh không phân biệt hoa thường như collation *_CI_AS cũ: cột
--    username và code_department (2 cột UNIQUE người dùng tự gõ) dùng
--    collation ICU ci_vi (không phân biệt hoa/thường, CÓ phân biệt dấu —
--    "CI_AS"). Không dùng citext vì citext = text (tham số $1::text) lại so
--    sánh phân biệt hoa thường; collation của cột thì luôn được áp dụng.
--    Hạn chế: LIKE/ILIKE không chạy trên cột collation này (PostgreSQL < 18) —
--    cần thì viết col COLLATE "default" LIKE ...
--  • Bổ sung CHECK cho status/department_access_type: bản SQL Server định
--    nghĩa nhầm thành TÊN của DEFAULT constraint nên chưa từng có hiệu lực.
--    Dữ liệu hiện tại (2026-11-04) đã hợp lệ với các CHECK này.
-- ============================================================================

-- File lưu UTF-8. psql trên Windows mặc định đọc theo bảng mã console (WIN1252)
-- → tiếng Việt lỗi "byte sequence 0x.. in encoding WIN1252". Ép UTF-8 cho phiên này:
SET client_encoding = 'UTF8';
BEGIN;

CREATE COLLATION IF NOT EXISTS ci_vi (
	provider = icu,
	locale = 'vi-VN-u-ks-level2',
	deterministic = false
);

-- ─── Danh mục ───────────────────────────────────────────────────────────────

CREATE TABLE departments (
	id_department   integer      GENERATED BY DEFAULT AS IDENTITY,
	name_department text         NOT NULL,
	code_department varchar(10)  COLLATE ci_vi NULL,
	bed_count       smallint     NULL,
	coef_level_1    numeric(5,4) NOT NULL,
	coef_level_2    numeric(5,4) NOT NULL,
	coef_level_3    numeric(5,4) NOT NULL,
	coef_total      numeric(5,4) NOT NULL,
	total_staff     smallint     NULL,
	status          varchar(10)  NOT NULL DEFAULT 'active',
	created_at      timestamptz  NOT NULL DEFAULT now(),
	updated_at      timestamptz  NULL     DEFAULT now(),
	formula_type    varchar(20)  NULL,
	fixed_staff_add numeric(5,1) NULL,
	dept_group      varchar(10)  NOT NULL DEFAULT 'ward',
	CONSTRAINT pk_departments PRIMARY KEY (id_department),
	CONSTRAINT ck_departments_status CHECK (status IN ('active', 'inactive'))
);
CREATE UNIQUE INDEX uq_departments_code ON departments (code_department)
	WHERE code_department IS NOT NULL;

CREATE TABLE roles (
	id_role                integer      GENERATED BY DEFAULT AS IDENTITY,
	name_role              varchar(100) NOT NULL,
	description            text         NULL,
	icon                   varchar(20)  NULL,
	color                  varchar(20)  NULL,
	is_system              boolean      NOT NULL DEFAULT false,
	department_access_type varchar(10)  NOT NULL DEFAULT 'own',
	created_at             timestamptz  NOT NULL DEFAULT now(),
	updated_at             timestamptz  NULL     DEFAULT now(),
	CONSTRAINT pk_roles PRIMARY KEY (id_role),
	CONSTRAINT ck_roles_department_access_type
		CHECK (department_access_type IN ('all', 'assigned', 'own'))
);

CREATE TABLE permissions (
	id_permission   integer      GENERATED BY DEFAULT AS IDENTITY,
	code_permission varchar(100) NOT NULL,
	label           varchar(200) NOT NULL,
	group_name      varchar(200) NULL,
	sort_order      smallint     NOT NULL DEFAULT 0,
	CONSTRAINT pk_permissions PRIMARY KEY (id_permission)
);

CREATE TABLE role_permissions (
	id_role       integer NOT NULL,
	id_permission integer NOT NULL,
	is_granted    boolean NOT NULL DEFAULT false,
	CONSTRAINT pk_role_permissions PRIMARY KEY (id_role, id_permission),
	CONSTRAINT fk_role_permissions_roles FOREIGN KEY (id_role)
		REFERENCES roles (id_role) ON DELETE CASCADE,
	CONSTRAINT fk_role_permissions_permissions FOREIGN KEY (id_permission)
		REFERENCES permissions (id_permission) ON DELETE CASCADE
);
CREATE INDEX ix_rolepermissions_permission ON role_permissions (id_permission);

CREATE TABLE role_department_access (
	id_role       integer NOT NULL,
	id_department integer NOT NULL,
	CONSTRAINT pk_role_department_access PRIMARY KEY (id_role, id_department),
	CONSTRAINT fk_role_department_access_roles FOREIGN KEY (id_role)
		REFERENCES roles (id_role) ON DELETE CASCADE,
	CONSTRAINT fk_role_department_access_departments FOREIGN KEY (id_department)
		REFERENCES departments (id_department) ON DELETE CASCADE
);
CREATE INDEX ix_rda_department ON role_department_access (id_department);

-- ─── Người dùng & phân quyền theo khoa ──────────────────────────────────────

CREATE TABLE users (
	id_user            integer      GENERATED BY DEFAULT AS IDENTITY,
	username           varchar(50)  COLLATE ci_vi NOT NULL,
	password           varchar(255) NOT NULL,
	user_code          varchar(10)  NULL,
	full_name          varchar(150) NOT NULL,
	id_department      integer      NULL,
	position           varchar(100) NULL,
	id_role            integer      NOT NULL,
	status             varchar(10)  NOT NULL DEFAULT 'active',
	created_at         timestamptz  NOT NULL DEFAULT now(),
	updated_at         timestamptz  NULL     DEFAULT now(),
	-- Bảo mật (trước đây do src/config/securitySchema.js ALTER thêm lúc khởi động)
	failed_login_count integer      NOT NULL DEFAULT 0,
	locked_until       timestamptz  NULL,
	lockout_level      integer      NOT NULL DEFAULT 0,
	totp_secret        varchar(255) NULL,
	totp_enabled       boolean      NOT NULL DEFAULT false,
	totp_verified_at   timestamptz  NULL,
	totp_last_step     bigint       NULL,
	-- Mật khẩu do quản trị đặt (tạo TK / đặt lại) → phải đổi ở lần đăng nhập
	-- tới; password_changed_at dùng để tính hạn của mật khẩu tạm.
	must_change_password boolean    NOT NULL DEFAULT false,
	password_changed_at  timestamptz NULL,
	CONSTRAINT pk_users PRIMARY KEY (id_user),
	CONSTRAINT ck_users_status CHECK (status IN ('active', 'inactive')),
	CONSTRAINT fk_users_departments FOREIGN KEY (id_department)
		REFERENCES departments (id_department),
	CONSTRAINT fk_users_roles FOREIGN KEY (id_role)
		REFERENCES roles (id_role)
);
CREATE UNIQUE INDEX uq_users_username ON users (username);
CREATE INDEX ix_users_id_department ON users (id_department);
CREATE INDEX ix_users_id_role ON users (id_role);

CREATE TABLE user_department_access (
	id_user       integer NOT NULL,
	id_department integer NOT NULL,
	CONSTRAINT pk_user_department_access PRIMARY KEY (id_user, id_department),
	CONSTRAINT fk_uda_users FOREIGN KEY (id_user)
		REFERENCES users (id_user) ON DELETE CASCADE,
	CONSTRAINT fk_uda_departments FOREIGN KEY (id_department)
		REFERENCES departments (id_department) ON DELETE CASCADE
);
CREATE INDEX ix_uda_department ON user_department_access (id_department);

CREATE TABLE user_dept_permissions (
	id_user       integer NOT NULL,
	id_department integer NOT NULL,
	can_edit      boolean NOT NULL DEFAULT false,
	can_delete    boolean NOT NULL DEFAULT false,
	can_export    boolean NOT NULL DEFAULT false,
	CONSTRAINT pk_user_dept_permissions PRIMARY KEY (id_user, id_department),
	CONSTRAINT fk_udp_users FOREIGN KEY (id_user)
		REFERENCES users (id_user) ON DELETE CASCADE,
	CONSTRAINT fk_udp_departments FOREIGN KEY (id_department)
		REFERENCES departments (id_department) ON DELETE CASCADE
);
CREATE INDEX ix_udp_department ON user_dept_permissions (id_department);

-- ─── Cấu hình công thức theo khoa ───────────────────────────────────────────

CREATE TABLE dept_tt03_config (
	id               integer      GENERATED BY DEFAULT AS IDENTITY,
	id_department    integer      NOT NULL,
	formula_type     varchar(20)  NOT NULL DEFAULT 'standard',
	patient_ratio    numeric(4,3) NOT NULL DEFAULT 0.600,
	shift_divisor    smallint     NULL,
	shift_multiplier smallint     NULL,
	fixed_add        numeric(5,1) NULL     DEFAULT 0,
	note             varchar(200) NULL,
	created_at       timestamptz  NOT NULL DEFAULT now(),
	updated_at       timestamptz  NULL     DEFAULT now(),
	CONSTRAINT pk_dept_tt03_config PRIMARY KEY (id),
	CONSTRAINT uq_dept_tt03_config_dept UNIQUE (id_department),
	-- TINYINT cũ
	CONSTRAINT ck_dept_tt03_shift_divisor CHECK (shift_divisor BETWEEN 0 AND 255),
	CONSTRAINT ck_dept_tt03_shift_multiplier CHECK (shift_multiplier BETWEEN 0 AND 255),
	CONSTRAINT fk_dept_tt03_config_departments FOREIGN KEY (id_department)
		REFERENCES departments (id_department) ON DELETE CASCADE
);

CREATE TABLE dept_recommended_config (
	id               integer      GENERATED BY DEFAULT AS IDENTITY,
	id_department    integer      NOT NULL,
	formula_type     varchar(20)  NOT NULL DEFAULT 'coef',
	coef_l1          numeric(5,4) NOT NULL DEFAULT 0.5000,
	coef_l2          numeric(5,4) NOT NULL DEFAULT 0.1040,
	coef_l3          numeric(5,4) NOT NULL DEFAULT 0.1040,
	outpatient_ratio numeric(5,4) NULL,
	fixed_add        numeric(6,1) NOT NULL DEFAULT 0.0,
	note             varchar(300) NULL,
	created_at       timestamptz  NOT NULL DEFAULT now(),
	updated_at       timestamptz  NULL,
	CONSTRAINT pk_dept_recommended_config PRIMARY KEY (id),
	CONSTRAINT uq_drc_department UNIQUE (id_department),
	CONSTRAINT fk_drc_departments FOREIGN KEY (id_department)
		REFERENCES departments (id_department) ON DELETE CASCADE
);

-- ─── Báo cáo hằng ngày ──────────────────────────────────────────────────────

CREATE TABLE daily_reports (
	id_report   integer     GENERATED BY DEFAULT AS IDENTITY,
	report_code varchar(50) NULL,
	report_date date        NULL,
	created_by  integer     NOT NULL,
	created_at  timestamptz NOT NULL DEFAULT now(),
	updated_at  timestamptz NULL     DEFAULT now(),
	CONSTRAINT pk_daily_reports PRIMARY KEY (id_report),
	CONSTRAINT fk_daily_reports_users FOREIGN KEY (created_by)
		REFERENCES users (id_user)
);
CREATE INDEX ix_dailyreports_created_by ON daily_reports (created_by);
CREATE INDEX ix_dailyreports_report_date ON daily_reports (report_date DESC);

-- Tên cũ: [Report_Department_Records ] (có dấu cách ở cuối)
CREATE TABLE report_department_records (
	id                     integer       GENERATED BY DEFAULT AS IDENTITY,
	id_report              integer       NOT NULL,
	id_department          integer       NOT NULL,
	sort_order             smallint      NULL,
	patient_level_1        smallint      NULL,
	patient_level_2        smallint      NULL,
	patient_level_3        smallint      NULL,
	total_patients         smallint      NULL,
	outpatient_cnt         smallint      NULL,
	total_staff            smallint      NULL,
	staff_on_duty          numeric(10,4) NULL,
	staff_long_leave       numeric(10,4) NULL,
	staff_working          numeric(10,4) NULL,
