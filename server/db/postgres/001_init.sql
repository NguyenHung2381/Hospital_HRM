-- ─── Bảo mật / phiên đăng nhập ──────────────────────────────────────────────

CREATE TABLE usersessions (
	jti          char(32)     NOT NULL,
	id_user      integer      NOT NULL,
	ip_address   varchar(64)  NULL,
	user_agent   varchar(255) NULL,
	created_at   timestamptz  NOT NULL DEFAULT now(),
	last_seen_at timestamptz  NULL,
	expires_at   timestamptz  NOT NULL,
	revoked_at   timestamptz  NULL,
	CONSTRAINT pk_usersessions PRIMARY KEY (jti)
);
CREATE INDEX ix_usersessions_user ON usersessions (id_user, expires_at);

CREATE TABLE securityevents (
	id          bigint        GENERATED BY DEFAULT AS IDENTITY,
	event_type  varchar(50)   NOT NULL,
	actor_id    integer       NULL,
	target_type varchar(50)   NULL,
	target_id   varchar(50)   NULL,
	ip_address  varchar(64)   NULL,
	user_agent  varchar(255)  NULL,
	detail      varchar(1000) NULL,
	created_at  timestamptz   NOT NULL DEFAULT now(),
	CONSTRAINT pk_securityevents PRIMARY KEY (id)
);

CREATE TABLE trusteddevices (
	device_id    char(32)    NOT NULL,
	id_user      integer     NOT NULL,
	failed_count integer     NOT NULL DEFAULT 0,
	created_at   timestamptz NOT NULL DEFAULT now(),
	last_used_at timestamptz NOT NULL DEFAULT now(),
	CONSTRAINT pk_trusteddevices PRIMARY KEY (device_id, id_user)
);
CREATE INDEX ix_trusteddevices_user ON trusteddevices (id_user);

-- Bảng có trong DB cũ nhưng code HRM hiện KHÔNG dùng (3 dòng, 2026-11-04).
-- Giữ lại để không mất dữ liệu; có thể bỏ sau khi xác nhận không hệ thống nào khác dùng.
CREATE TABLE auth_sessions (
	id_session        char(32)       NOT NULL,
	id_user           integer        NOT NULL,
	client_type       varchar(10)    NOT NULL,
	remember          boolean        NOT NULL DEFAULT false,
	refresh_hash      char(64)       NOT NULL,
	prev_refresh_hash char(64)       NULL,
	rotated_at        timestamptz(0) NULL,
	pwf               varchar(32)    NOT NULL,
	ip_address        varchar(64)    NULL,
	user_agent        varchar(300)   NULL,
	created_at        timestamptz(0) NOT NULL DEFAULT now(),
	last_used_at      timestamptz(0) NOT NULL DEFAULT now(),
	expires_at        timestamptz(0) NOT NULL,
	max_expires_at    timestamptz(0) NOT NULL,
	revoked_at        timestamptz(0) NULL,
	revoked_reason    varchar(50)    NULL,
	CONSTRAINT pk_auth_sessions PRIMARY KEY (id_session),
	CONSTRAINT fk_auth_sessions_users FOREIGN KEY (id_user)
		REFERENCES users (id_user) ON DELETE CASCADE
);
CREATE UNIQUE INDEX ux_auth_sessions_refresh ON auth_sessions (refresh_hash);
CREATE INDEX ix_auth_sessions_prev ON auth_sessions (prev_refresh_hash);
CREATE INDEX ix_auth_sessions_user ON auth_sessions (id_user, revoked_at, expires_at);

COMMIT;
